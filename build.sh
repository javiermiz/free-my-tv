#!/usr/bin/env bash
# Builds FreeMyTV.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-34). See README.md.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-34\""; exit 1; }
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Libraries: ExoPlayer (Media3) for the player, downloaded once into libs/ (Google's Maven, then Maven Central)
LIBS=(
  androidx.media3:media3-exoplayer:1.4.1:aar androidx.media3:media3-common:1.4.1:aar
  androidx.media3:media3-container:1.4.1:aar androidx.media3:media3-datasource:1.4.1:aar
  androidx.media3:media3-decoder:1.4.1:aar androidx.media3:media3-extractor:1.4.1:aar
  androidx.media3:media3-database:1.4.1:aar androidx.annotation:annotation:1.3.0:jar
  androidx.annotation:annotation-experimental:1.3.1:aar androidx.collection:collection:1.2.0:jar
  com.google.guava:guava:33.0.0-android:jar com.google.guava:failureaccess:1.0.2:jar
)
mkdir -p libs
for lib in "${LIBS[@]}"; do
  IFS=: read -r group name version ext <<<"$lib"
  jar="libs/$name-$version.jar"
  [ -f "$jar" ] && continue
  path="${group//.//}/$name/$version/$name-$version.$ext"
  curl -sfL -o "libs/download.$ext" "https://dl.google.com/dl/android/maven2/$path" \
    || curl -sfL -o "libs/download.$ext" "https://repo1.maven.org/maven2/$path" \
    || { echo "Couldn't download $lib"; exit 1; }
  if [ "$ext" = aar ]; then unzip -p "libs/download.aar" classes.jar >"$jar"; else mv "libs/download.jar" "$jar"; fi
  rm -f "libs/download.$ext"
done
LIBJARS="$(ls libs/*.jar | tr '\n' ':')"

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: add your TMDB key and your city there (optional), then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude 40.7128)"
LON="$(number longitude -74.0060)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true

rm -rf out && mkdir -p out/gen/io/freemytv out/classes
cat > out/gen/io/freemytv/Config.java <<EOF
package io.freemytv;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$(prop tmdb_key '')";
    static final String STREMIO_KEY = "$(prop stremio_key '')";
    static final String YOUTUBE_KEY = "$(prop youtube_key '')";
    static final String TMDB_REGION = "$(prop tmdb_region US)";
    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String CURRENCY = "$(prop currency USD)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
}
EOF

# --- Build
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 31 --target-sdk-version 33 -A app/assets -0 ttf
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ:$LIBJARS" \
  -d out/classes $(find app/src out/gen -name '*.java')
"$BT/d8" --release --min-api 31 --lib "$AJ" --output out $(find out/classes -name '*.class') libs/*.jar
(cd out && zip -qj base.apk classes*.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep freemytv.keystore)
if [ ! -f freemytv.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore freemytv.keystore -alias freemytv -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass freemytv -keypass freemytv -dname "CN=Free My TV" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks freemytv.keystore --ks-pass pass:freemytv --key-pass pass:freemytv --out FreeMyTV.apk out/aligned.apk
echo "Built FreeMyTV.apk ($(du -h FreeMyTV.apk | cut -f1)). Install: adb install -r FreeMyTV.apk"
